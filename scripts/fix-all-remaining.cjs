// Apply for all locales (ps gets full, others get same for now)
const locales = ['sd', 'ps', 'pa', 'bal', 'skr', 'hno'];

for (const lang of locales) {
  console.log(`Fixing ${lang}.ts...`);
  let content = fs.readFileSync(`catalog/${lang}.ts`, 'utf8');
  const tr = T[lang] || T.ps; // fallback to ps translations
  let fixCount = 0;

  for (const [key, value] of Object.entries(tr)) {
    const regex = new RegExp(`("${key.replace(/\./g, '\\.')}":\\s*)"[^"]*"`, 'g');
    if (regex.test(content)) {
      content = content.replace(regex, `$1"${value}"`);
      fixCount++;
    }
  }

  fs.writeFileSync(`catalog/${lang}.ts`, content);
  console.log(`  Applied ${fixCount} fixes`);
}

console.log('\nDone!');
