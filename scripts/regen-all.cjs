for (const locale of locales) {
  console.log(`Generating ${locale.code}.ts...`);
  
  // Start with ur.ts
  let content = ur;
  
  // Replace header comment
  content = content.replace(
    /\/\*\*[\s\S]*?\*\//,
    `/** ${locale.name} — translations based on Urdu reference. RTL language. */`
  );
  
  // Replace export name
  content = content.replace(/export const ur/g, `export const ${locale.code}`);
  
  // Replace type definition
  content = content.replace(
    /export type CatalogKey = keyof typeof ur;/,
    `export type CatalogKey = keyof typeof ${locale.code};`
  );
  
  // Apply locale-specific word replacements (only in string values, not keys)
  const localeReplacements = replacements[locale.code] || [];
  for (const [from, to] of localeReplacements) {
    // Replace in string values only (after colon)
    const regex = new RegExp(`(:\\s*"[^"]*)${from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`, 'g');
    content = content.replace(regex, `$1${to}`);
  }
  
  fs.writeFileSync(`catalog/${locale.code}.ts`, content);
  console.log(`  Written ${locale.code}.ts`);
}

console.log('\nDone! All 6 locale files generated from ur.ts');
